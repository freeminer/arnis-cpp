inline constexpr int VANILLA_FLOOR = -64;

// The physical floor still bounds writes; the datum only translates vanilla's
// reference Y for cave shape and feature placement. This mirrors Rust's
// process-wide DATUM_Y, while retaining terrain-relative behavior by default.
inline std::atomic<int> &cave_datum_slot()
{
	static std::atomic<int> datum{std::numeric_limits<int>::min()};
	return datum;
}

// A One World tiled job may be generated by separate processes. The first
// piece publishes its terrain floor atomically; subsequent pieces use that
// same frame so cave features line up across piece boundaries.
inline int share_piece_datum(const std::filesystem::path &job_dir, int own)
{
	if (job_dir.empty())
		return own;
	std::error_code ec;
	std::filesystem::create_directories(job_dir, ec);
	const auto path = job_dir / "cave_datum_y";
	auto read = [&]() -> std::optional<int> {
		std::ifstream in(path);
		int value;
		if (in >> value) {
			char extra;
			if (!(in >> extra))
				return value;
		}
		return std::nullopt;
	};
	if (const auto existing = read())
		return *existing;
	static std::atomic<std::uint64_t> sequence{0};
	const auto stamp = std::chrono::steady_clock::now().time_since_epoch().count();
	const auto temporary =
			job_dir /
			("cave_datum_y." + std::to_string(stamp) + "." +
					std::to_string(sequence.fetch_add(1, std::memory_order_relaxed)));
	{
		std::ofstream out(temporary, std::ios::binary | std::ios::trunc);
		if (out)
			out << own << '\n';
		if (!out) {
			std::filesystem::remove(temporary, ec);
			return read().value_or(own);
		}
	}
	std::filesystem::create_hard_link(temporary, path, ec);
	std::filesystem::remove(temporary, ec);
	if (const auto shared = read())
		return *shared;
	return own;
}

inline std::atomic<int> &piece_cave_datum_slot()
{
	static std::atomic<int> datum{std::numeric_limits<int>::min()};
	return datum;
}

inline void set_piece_cave_datum(std::optional<int> y)
{
	piece_cave_datum_slot().store(
			y.value_or(std::numeric_limits<int>::min()), std::memory_order_relaxed);
}

inline void set_cave_datum(std::optional<int> y)
{
	cave_datum_slot().store(
			y.value_or(std::numeric_limits<int>::min()), std::memory_order_relaxed);
}

inline int cave_y_shift(int physical_floor_y)
{
	int datum = cave_datum_slot().load(std::memory_order_relaxed);
	if (datum == std::numeric_limits<int>::min())
		datum = piece_cave_datum_slot().load(std::memory_order_relaxed);
	return (datum == std::numeric_limits<int>::min() ? physical_floor_y : datum) -
		   VANILLA_FLOOR;
}

inline int cave_vy(int vanilla_y, int physical_floor_y)
{
	return vanilla_y + cave_y_shift(physical_floor_y);
}

inline bool cave_datum_pinned()
{
	return cave_datum_slot().load(std::memory_order_relaxed) !=
		   std::numeric_limits<int>::min();
}

inline bool piece_cave_datum_pinned()
{
	return piece_cave_datum_slot().load(std::memory_order_relaxed) !=
		   std::numeric_limits<int>::min();
}

enum class CaveTheme
{
	Normal,
	Lush,
	Dripstone,
	DeepDark,
	Mushroom,
	Ice,
	Amethyst,
	Volcanic
};

inline NormalNoise cave_theme_noise(std::int64_t seed, std::string_view name)
{
	auto factory = XoroRandom::from_seed(seed ^ 0x0DEC0DECL).fork_positional();
	auto random = factory.from_hash_of(name);
	return NormalNoise::create(random, -7, {1.0});
}

struct ThemeSelector
{
	NormalNoise lush;
	NormalNoise drip;
	NormalNoise sculk;
	NormalNoise shroom;
	NormalNoise ice;
	NormalNoise crystal;
	NormalNoise coral;
	NormalNoise volcanic;
	BiomeAmounts amounts;
	int y_shift;

	ThemeSelector(std::int64_t seed, BiomeAmounts biome_amounts, int floor_y) :
			lush(cave_theme_noise(seed, "lush_select")),
			drip(cave_theme_noise(seed, "dripstone_select")),
			sculk(cave_theme_noise(seed, "sculk_select")),
			shroom(cave_theme_noise(seed, "shroom_select")),
			ice(cave_theme_noise(seed, "ice_select")),
			crystal(cave_theme_noise(seed, "crystal_select")),
			coral(cave_theme_noise(seed, "coral_select")),
			volcanic(cave_theme_noise(seed, "volcanic_select")), amounts(biome_amounts),
			y_shift(cave_y_shift(floor_y))
	{
	}
	bool coral_zone(int x, int z) const
	{
		const double threshold = BiomeAmounts::effective_threshold(0.34, amounts.coral);
		return std::isfinite(threshold) && coral.get_value(x, 0.0, z) > threshold;
	}

	bool hit(const NormalNoise &noise, double threshold, double amount, double x,
			double z, double scale) const
	{
		return noise.get_value(x * scale, 0.0, z * scale) >
			   BiomeAmounts::effective_threshold(threshold, amount);
	}

	CaveTheme at(int x, int y, int z, int surface_y) const
	{
		constexpr double margin = 0.06;
		const int vanilla_y = y - y_shift;
		const int vanilla_surface = surface_y - y_shift;
		const double scale = vanilla_y < -30 ? 0.72 : 1.15;
		if (vanilla_y <= -40 &&
				hit(volcanic, 0.18 + margin, amounts.volcanic, x, z, scale))
			return CaveTheme::Volcanic;
		if (vanilla_y <= -35 && hit(sculk, 0.17 + margin, amounts.deepdark, x, z, scale))
			return CaveTheme::DeepDark;
		if (vanilla_y >= -36 && vanilla_surface >= 115 &&
				hit(ice, 0.20 + margin, amounts.ice, x, z, scale))
			return CaveTheme::Ice;
		if (hit(lush, 0.17 + margin, amounts.lush, x, z, scale))
			return CaveTheme::Lush;
		if (hit(drip, 0.18 + margin, amounts.dripstone, x, z, scale))
			return CaveTheme::Dripstone;
		if (hit(shroom, 0.21 + margin, amounts.mushroom, x, z, scale))
			return CaveTheme::Mushroom;
		if (hit(crystal, 0.25 + margin, amounts.amethyst, x, z, scale))
			return CaveTheme::Amethyst;
		return CaveTheme::Normal;
	}
};

inline const char *cave_theme_tag(CaveTheme theme)
{
	switch (theme) {
	case CaveTheme::Lush:
		return "lush";
	case CaveTheme::Dripstone:
		return "dripstone";
	case CaveTheme::DeepDark:
		return "deepdark";
	case CaveTheme::Mushroom:
		return "mushroom";
	case CaveTheme::Ice:
		return "ice";
	case CaveTheme::Amethyst:
		return "amethyst";
	case CaveTheme::Volcanic:
		return "volcanic";
	case CaveTheme::Normal:
	default:
		return "any";
	}
}
